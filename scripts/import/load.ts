// Turns staging.json (from report.ts) into one idempotent SQL script.
// Every row gets a deterministic id derived from its staging key, so running
// the script again updates the same rows instead of duplicating them.
//
// Usage: node scripts/import/load.ts <staging.json> <out.sql>
// Apply the SQL with scripts/supabase-sql.ts (Supabase) or psql (local).

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';

interface StagingFile {
  parties: { key: string; name: string; kind: string; roles: string[]; emails: string[]; phones: string[]; spellings: string[]; taxId?: string; address?: string; referral?: string }[];
  buildings: { key: string; country: string; city: string; project?: string; name: string; address?: string }[];
  properties: { key: string; sourceId: string; aliases: string[]; externalRefs: { source: string; key: string }[]; country: string; buildingKey: string; unitNo: string; floor?: string; sqm?: number; purchaseDate?: string; status: string }[];
  ownerships: { propertyKey: string; partyKey: string; sharePct: number; shareAssumed: boolean }[];
  leases: { propertyKey: string; tenantKey?: string; start: string; end?: string; rent: number; currency: string; deposit?: number; brokerage?: number; collectDay?: number; notes?: string }[];
  accounts: { ownerKey: string; country: string; currency: string; iban: string; bank: string }[];
}

const CITY_HE: Record<string, string> = {
  Kyiv: 'קייב', Odessa: 'אודסה', Batumi: 'בטומי', Tbilisi: 'טביליסי', Bucharest: 'בוקרשט',
};

// RFC 4122 version-5 style UUID from a name.
export function stableId(kind: string, key: string): string {
  const h = createHash('sha1').update(`seethefuture:${kind}:${key}`).digest();
  h[6] = (h[6] & 0x0f) | 0x50;
  h[8] = (h[8] & 0x3f) | 0x80;
  const x = h.subarray(0, 16).toString('hex');
  return `${x.slice(0, 8)}-${x.slice(8, 12)}-${x.slice(12, 16)}-${x.slice(16, 20)}-${x.slice(20)}`;
}

export function lit(v: unknown): string {
  if (v === undefined || v === null || v === '') return 'null';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  return `'${String(v).replace(/'/g, "''")}'`;
}

// Rows with the same id (the same lease or IBAN entered twice in Airtable)
// are written once; the first one wins.
function insert(table: string, cols: string[], allRows: unknown[][], conflict = 'id'): string {
  const seen = new Set<unknown>();
  const rows = allRows.filter((r) => !seen.has(r[0]) && seen.add(r[0]));
  if (!rows.length) return '';
  const values = rows.map((r) => `  (${r.map(lit).join(', ')})`).join(',\n');
  const updates = cols.filter((c) => c !== conflict).map((c) => `${c} = excluded.${c}`).join(', ');
  return `insert into app.${table} (${cols.join(', ')}) values\n${values}\non conflict (${conflict}) do update set ${updates};\n`;
}

export function buildSql(st: StagingFile): string {
  const out: string[] = ['-- Generated by scripts/import/load.ts. Safe to run more than once.', 'begin;'];
  const partyId = (k: string) => stableId('party', k);
  const propertyId = (k: string) => stableId('property', k);
  const partyKind = new Map(st.parties.map((p) => [p.key, p.kind]));

  // Geography ---------------------------------------------------------------
  const cities = new Map<string, { country: string; name: string }>();
  const projects = new Map<string, { cityKey: string; name: string }>();
  for (const b of st.buildings) {
    const cityKey = `${b.country}|${b.city}`;
    cities.set(cityKey, { country: b.country, name: b.city });
    if (b.project) projects.set(`${cityKey}|${b.project}`, { cityKey, name: b.project });
  }
  out.push(insert('cities', ['id', 'country_code', 'name_he', 'name_en'],
    [...cities].map(([k, c]) => [stableId('city', k), c.country, CITY_HE[c.name] ?? c.name, c.name])));
  out.push(insert('projects', ['id', 'city_id', 'name'],
    [...projects].map(([k, p]) => [stableId('project', k), stableId('city', p.cityKey), p.name])));
  out.push(insert('buildings', ['id', 'city_id', 'project_id', 'name', 'address'],
    st.buildings.map((b) => {
      const cityKey = `${b.country}|${b.city}`;
      return [stableId('building', b.key), stableId('city', cityKey),
        b.project ? stableId('project', `${cityKey}|${b.project}`) : null, b.name, b.address];
    })));

  // Parties -------------------------------------------------------------------
  out.push(insert('parties', ['id', 'kind', 'display_name', 'email', 'phone', 'tax_id', 'address', 'notes'],
    st.parties.map((p) => [partyId(p.key), p.kind, p.name, p.emails[0], p.phones[0], p.taxId, p.address,
      [p.emails.length > 1 ? `Other emails: ${p.emails.slice(1).join(', ')}` : '',
        p.phones.length > 1 ? `Other phones: ${p.phones.slice(1).join(', ')}` : '',
        p.referral ? `Referral: ${p.referral}` : ''].filter(Boolean).join('\n')])));
  const roleRows = st.parties.flatMap((p) => p.roles.map((r) => [partyId(p.key), r]));
  if (roleRows.length) {
    out.push(`insert into app.party_roles (party_id, role) values\n${roleRows.map((r) => `  (${r.map(lit).join(', ')})`).join(',\n')}\non conflict do nothing;\n`);
  }

  // Properties ----------------------------------------------------------------
  out.push(insert('properties', ['id', 'building_id', 'unit_no', 'floor', 'sqm', 'status'],
    st.properties.map((p) => [propertyId(p.key), stableId('building', p.buildingKey), p.unitNo, p.floor, p.sqm, p.status])));

  // Names each source uses, so later imports and reports find the same rows.
  // Georgian record names repeat when an owner has two units in one project;
  // those get the unit number appended to stay unique.
  const nameUse = new Map<string, number>();
  for (const p of st.properties) for (const n of [p.sourceId, ...p.aliases]) nameUse.set(`${p.country}|${n}`, (nameUse.get(`${p.country}|${n}`) ?? 0) + 1);
  const refs: unknown[][] = [];
  for (const p of st.properties) {
    const src = `airtable_${p.country.toLowerCase()}`;
    for (const n of [p.sourceId, ...p.aliases]) {
      const name = nameUse.get(`${p.country}|${n}`)! > 1 ? `${n} [${p.unitNo}]` : n;
      refs.push([stableId('ref', `${src}|property|${name}`), 'property', propertyId(p.key), src, name]);
    }
    for (const r of p.externalRefs) refs.push([stableId('ref', `${r.source}|property|${r.key}`), 'property', propertyId(p.key), r.source, r.key]);
  }
  for (const p of st.parties) {
    for (const name of p.spellings) refs.push([stableId('ref', `airtable|party|${name}`), 'party', partyId(p.key), 'airtable', name]);
  }
  out.push(insert('external_refs', ['id', 'entity_type', 'entity_id', 'source', 'external_key'], refs));

  // Ownership, leases, bank accounts -------------------------------------------
  const purchase = new Map(st.properties.map((p) => [p.key, p.purchaseDate]));
  out.push(insert('ownerships', ['id', 'property_id', 'party_id', 'share_pct', 'valid_from', 'notes'],
    st.ownerships.map((o) => [stableId('ownership', `${o.propertyKey}|${o.partyKey}`), propertyId(o.propertyKey), partyId(o.partyKey),
      o.sharePct, purchase.get(o.propertyKey) ?? '2026-01-01',
      [o.shareAssumed ? 'Share assumed equal (Airtable has no split).' : '',
        purchase.get(o.propertyKey) ? '' : 'Start date unknown; set to the opening date.'].filter(Boolean).join(' ')])));

  out.push(insert('leases',
    ['id', 'property_id', 'tenant_party_id', 'start_date', 'end_date', 'rent_amount', 'rent_currency',
      'deposit_amount', 'deposit_currency', 'brokerage_fee', 'brokerage_currency', 'collect_day', 'withholding_tax_pct', 'notes'],
    st.leases.map((l) => {
      // Romania: 8% withheld when the tenant is a company (SPEC decision 19).
      const tax = l.propertyKey.startsWith('RO|') && l.tenantKey && partyKind.get(l.tenantKey) === 'company' ? 8 : 0;
      const end = l.end && l.end >= l.start ? l.end : undefined;
      return [stableId('lease', `${l.propertyKey}|${l.start}|${l.tenantKey ?? ''}`), propertyId(l.propertyKey),
        l.tenantKey ? partyId(l.tenantKey) : null, l.start, end, l.rent, l.currency,
        l.deposit, l.deposit !== undefined ? l.currency : null, l.brokerage, l.brokerage !== undefined ? l.currency : null,
        l.collectDay && l.collectDay <= 31 ? l.collectDay : null, tax,
        [l.notes, l.end && !end ? `End date in Airtable (${l.end}) is before the start.` : ''].filter(Boolean).join('\n')];
    })));

  out.push(insert('accounts', ['id', 'holder_party_id', 'beneficiary_party_id', 'country_code', 'currency', 'kind', 'bank_name', 'iban'],
    st.accounts.map((a) => [stableId('account', a.iban), partyId(a.ownerKey), partyId(a.ownerKey), a.country, a.currency, 'client_bank', a.bank, a.iban])));

  out.push('commit;');
  return out.filter(Boolean).join('\n');
}

if (import.meta.main) {
  const [stagingPath, outPath] = process.argv.slice(2);
  if (!stagingPath || !outPath) {
    console.error('usage: node scripts/import/load.ts <staging.json> <out.sql>');
    process.exit(1);
  }
  writeFileSync(outPath, buildSql(JSON.parse(readFileSync(stagingPath, 'utf8'))));
  console.log(`wrote ${outPath}`);
}
